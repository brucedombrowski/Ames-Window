#!/usr/bin/env bash
# Generate the verification matrix docs/VER-2026-001.md from the evidence
# anchors in docs/REQ-2026-001.json.
#
#   scripts/ver.sh            # regenerate
#   scripts/ver.sh --check    # fail if the committed matrix is out of date
#
# Each requirement in the REQ document either lists evidence anchors (a file
# and a fixed string that must appear in it) or is marked "open" with a
# tracking issue. This script locates every anchor, records file:line, and
# fails if any anchor is missing, which is how a stale matrix is caught
# (systems-engineering Phase 4; NIST SP 800-53 SA-11). The output depends only
# on the REQ document and the files it points at, so it is reproducible and
# is committed, with CI running --check.
#
# Requires: jq, grep.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

req="docs/REQ-2026-001.json"
out="docs/VER-2026-001.md"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

req_id="$(jq -r .document_id "$req")"
req_ver="$(jq -r .version "$req")"
ver_id="VER-${req_id#REQ-}"

missing=0
pass=0
open=0

{
cat <<EOF
# $ver_id: Verification matrix

Generated by \`scripts/ver.sh\` from [\`$req\`](REQ-2026-001.json) version $req_ver.
Do not edit by hand; CI fails if this file does not match a fresh run.

Each requirement maps to the file and line where it is implemented. Method is
the verification method the requirement specifies. **PASS** means every
evidence anchor was found. **OPEN** means the requirement is not yet
implemented and names the tracking issue.

Traceability chain: standard → requirement → file:line → method → this entry.

| Requirement | Standard | Evidence | File:Line | Method | Status |
|---|---|---|---|---|---|
EOF

jq -c '.categories[].requirements[]' "$req" | while IFS= read -r r; do
  id="$(jq -r .id <<<"$r")"
  std="$(jq -r .standard <<<"$r")"
  method="$(jq -r .verification <<<"$r")"
  status="$(jq -r '.status // "evidence"' <<<"$r")"
  if [[ "$status" == "open" ]]; then
    tracking="$(jq -r '.tracking // "none"' <<<"$r")"
    note="$(jq -r '.note // ""' <<<"$r")"
    printf '| %s | %s | %s | tracked in %s | %s | **OPEN** |\n' "$id" "$std" "$note" "$tracking" "$method"
    echo "OPEN $id" >&2
    continue
  fi
  n="$(jq '.evidence | length' <<<"$r")"
  for ((i = 0; i < n; i++)); do
    file="$(jq -r ".evidence[$i].file" <<<"$r")"
    pattern="$(jq -r ".evidence[$i].pattern" <<<"$r")"
    line="$(grep -n -F -m1 -- "$pattern" "$file" 2>/dev/null | cut -d: -f1 || true)"
    label="$id"
    [[ $i -gt 0 ]] && label=""
    if [[ -z "$line" ]]; then
      printf '| %s | %s | `%s` | %s: **not found** | %s | **FAIL** |\n' "$label" "$std" "$pattern" "$file" "$method"
      echo "MISSING $id: '$pattern' not in $file" >&2
    else
      printf '| %s | %s | `%s` | `%s:%s` | %s | PASS |\n' "$label" "$std" "$pattern" "$file" "$line" "$method"
      echo "PASS $id $file:$line" >&2
    fi
  done
done 2>"$tmp.log"

cat <<EOF

## Summary

| Status | Count |
|---|---|
| Requirements with all evidence found | $(grep -c '^PASS' "$tmp.log" | awk '{print $1}') anchors across $(grep '^PASS' "$tmp.log" | awk '{print $2}' | sort -u | wc -l | tr -d ' ') requirements |
| Open requirements | $(grep -c '^OPEN' "$tmp.log" | tr -d ' ') |
| Missing evidence | $(grep -c '^MISSING' "$tmp.log" | tr -d ' ') |

Open requirements are defects against the baseline until closed; each names
its tracking issue. Missing evidence means the matrix is stale and the build
fails.
EOF
} > "$tmp"

missing="$(grep -c '^MISSING' "$tmp.log" || true)"
if [[ "$missing" -gt 0 ]]; then
  grep '^MISSING' "$tmp.log" >&2
  echo "$missing evidence anchor(s) not found. Fix $req or the code." >&2
  exit 1
fi

if [[ "${1:-}" == "--check" ]]; then
  if cmp -s "$tmp" "$out"; then
    echo "$out is up to date."
  else
    diff -u "$out" "$tmp" | head -40 || true
    echo "$out is stale. Run scripts/ver.sh and commit the result." >&2
    exit 1
  fi
else
  mv "$tmp" "$out"
  echo "Wrote $out: $(grep -c '^PASS' "$tmp.log") anchors found, $(grep -c '^OPEN' "$tmp.log" || true) open."
fi
