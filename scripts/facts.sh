#!/usr/bin/env bash
# Write docs/facts.json: the numbers that documents and briefings quote.
#
#   scripts/facts.sh            # regenerate
#   scripts/facts.sh --check    # fail if the committed file is out of date
#
# Every count here is read from the repository, never typed. Prose that
# quotes a number cites this file. The file deliberately omits the commit
# hash so that it can be committed without describing the previous commit
# (DM-2026-003); CI checks it the way it checks the SBOM.
#
# Requires: jq, cargo (for the test count).
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

out="docs/facts.json"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

sbom="sbom.cdx.json"
req="docs/REQ-2026-001.json"
risk="docs/RISK-2026-001.json"

version="$(sed -n 's/^version = "\(.*\)"$/\1/p' Cargo.toml | head -1)"
components="$(jq '.components | length' "$sbom")"
licence_expressions="$(jq '[.components[].licenses[]? | (.expression // .license.id)] | unique | length' "$sbom")"
licences_allowed="$(sed -n '/^allow = \[/,/^\]/p' deny.toml | grep -c '^  "')"
banned_crates="$(grep -cE '^\s*\{ crate = ' deny.toml || true)"
accepted_advisories="$(grep -cE '^\s*\{ id = "RUSTSEC' deny.toml || true)"
tests="$(cargo test --workspace -q -- --list 2>/dev/null | grep -c ': test$' || true)"
workspace_crates="$(grep -c '^crates/' <<<"$(sed -n 's/^members = \[\(.*\)\]$/\1/p' Cargo.toml | tr ',' '\n' | tr -d ' "')")"

jq -n \
  --arg version "$version" \
  --argjson components "$components" \
  --argjson licence_expressions "$licence_expressions" \
  --argjson licences_allowed "$licences_allowed" \
  --argjson banned_crates "$banned_crates" \
  --argjson accepted_advisories "$accepted_advisories" \
  --argjson tests "$tests" \
  --argjson workspace_crates "$workspace_crates" \
  --slurpfile req "$req" \
  --slurpfile risk "$risk" \
  '{
    note: "Generated by scripts/facts.sh. Quote these; do not type numbers into documents.",
    software: {
      version: $version,
      workspace_crates: $workspace_crates,
      unit_tests: $tests
    },
    supply_chain: {
      third_party_components: $components,
      distinct_licence_expressions: $licence_expressions,
      licences_allowed: $licences_allowed,
      networking_crates_banned: $banned_crates,
      accepted_advisories: $accepted_advisories
    },
    requirements: {
      document: $req[0].document_id,
      version: $req[0].version,
      total: ([$req[0].categories[].requirements[]] | length),
      with_evidence: ([$req[0].categories[].requirements[] | select(.evidence)] | length),
      derived: ([$req[0].categories[].requirements[] | select(.status == "derived")] | length),
      open: ([$req[0].categories[].requirements[] | select(.status == "open")] | length),
      evidence_anchors: ([$req[0].categories[].requirements[] | .evidence // [] | length] | add)
    },
    risks: {
      document: $risk[0].document_id,
      total: ($risk[0].risks | length),
      open: ([$risk[0].risks[] | select(.status == "open")] | length),
      accepted: ([$risk[0].risks[] | select(.response == "accept")] | length)
    }
  }' > "$tmp"

if [[ "${1:-}" == "--check" ]]; then
  if cmp -s "$tmp" "$out"; then
    echo "$out is up to date."
  else
    diff -u "$out" "$tmp" || true
    echo "$out is stale. Run scripts/facts.sh and commit the result." >&2
    exit 1
  fi
else
  mv "$tmp" "$out"
  echo "Wrote $out"; cat "$out"
fi
