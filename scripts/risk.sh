#!/usr/bin/env bash
# Render docs/RISK-2026-001.md from docs/RISK-2026-001.json.
#
#   scripts/risk.sh            # regenerate
#   scripts/risk.sh --check    # fail if the committed rendering is out of date
#
# The JSON is the register (NIST SP 800-30 Rev. 1 vocabulary); the Markdown is
# a readable view of it, generated so the two cannot disagree. It also checks
# that every control a risk names exists in REQ-2026-001.json.
#
# Requires: jq.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

reg="docs/RISK-2026-001.json"
req="docs/REQ-2026-001.json"
out="docs/RISK-2026-001.md"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

# Every control must be a requirement id that exists.
bad="$(jq -r --slurpfile r "$req" '
  [$r[0].categories[].requirements[].id] as $ids
  | .risks[] | .id as $rid | .controls[] | select(. as $c | $ids | index($c) | not) | "\($rid) names unknown control \(.)"' "$reg")"
if [[ -n "$bad" ]]; then echo "$bad" >&2; exit 1; fi

{
jq -r '
"# \(.document_id): \(.title)",
"",
"Generated by `scripts/risk.sh` from [`docs/RISK-2026-001.json`](RISK-2026-001.json) version \(.version). Do not edit by hand.",
"",
.method,
"",
"Scale: \(.scale).",
"",
"## Register",
"",
"| Id | Risk | Likelihood | Impact | Controls | Residual | Response | Owner | Status |",
"|---|---|---|---|---|---|---|---|---|",
(.risks[] | "| \(.id) | **\(.title)** | \(.likelihood) | \(.impact) | \(.controls | join(", ") | if . == "" then "none" else . end) | \(.residual_likelihood) / \(.residual_impact) | \(.response) | \(.owner) | \(.status) |"),
"",
"## Detail",
"",
(.risks[] |
  "### \(.id): \(.title)",
  "",
  "**Statement.** \(.statement)",
  "",
  "**Source.** \(.source)",
  "",
  "**Controls.** \(.control_note)",
  "",
  "**Review.** \(.review)",
  "",
  "**References.** \(.references | join(", "))",
  ""
),
"## Summary",
"",
"| | Count |",
"|---|---|",
"| Risks | \(.risks | length) |",
"| Open | \([.risks[] | select(.status == "open")] | length) |",
"| Closed | \([.risks[] | select(.status == "closed")] | length) |",
"| Accepted (response = accept) | \([.risks[] | select(.response == "accept")] | length) |"
' "$reg"
} > "$tmp"

if [[ "${1:-}" == "--check" ]]; then
  if cmp -s "$tmp" "$out"; then
    echo "$out is up to date."
  else
    diff -u "$out" "$tmp" | head -40 || true
    echo "$out is stale. Run scripts/risk.sh and commit the result." >&2
    exit 1
  fi
else
  mv "$tmp" "$out"
  echo "Wrote $out ($(jq '.risks | length' "$reg") risks)."
fi
